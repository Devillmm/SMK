# ESCAPE SEQUENCES IN PYTHON

# "\n" - NEW LINE
print("NEW LINE:")
print("Manikandan\nSuriyakumar")
print()

# "\t" - TAB SPACE
print("TAB SPACE:")
print("Python\t\tProgramming")
print()

# "\'" - APOSTROPHE
print("APOSTROPHE:")
print('It\'s My Phone')
print("It's My Phone")
print()

# '\"' - DOUBLE QUOTES
print("DOUBLE QUOTES:")
print("He said, \"This is Mani's Laptop\"")
print('He said, "This is Mani\'s Laptop"')
print()

# "\\" - BACK SLASH
print("\\ - Back Slash")
print("/ - Forward Slash")
print()

