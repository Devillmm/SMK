# USER INPUT 
# SIMPLE DATATYPES - INTEGER, FLOAT, STRING, BOOLEAN by using GET INPUT FROM USER

# GET STRING INPUT FROM THE USER [Default]
User_Name = input("Enter Your Name: ")
print("STRING DATATYPE: ",User_Name)

# GET INTEGER INPUT FROM THE USER
Num = int(input("Enter Your Age: "))
print("INTEGER DATATYPE: ",Num)

# GET FLOAT INPUT FROM THE USER
salary = float(input("Enter Your Salary: "))
print("FLOAT DATATYPE: ",salary)

# GET BOOLEAN INPUT FROM THE USER
id = bool(input("Are you received your ID card: "))
print("BOOLEAN DATATYPE: ",id)
