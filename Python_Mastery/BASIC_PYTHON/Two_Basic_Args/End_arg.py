# Print a Statement using "END ARGUMENT"
# END ARGUMENT --> end = "\n"

# Without END ARGUMENT
print("Hello World")
print("Python")

print()

# With END ARGUMENT - end = "\n"
print("Hello World",end = "\n")
print("Python")

print()

# with END ARGUMENT - end = " "
print("Manikandan",end = " ")
print("SuriyaKumar")

print()

# with END ARGUMENT - end = "..."
print("Hi...Hi",end = "...")