# Print a Statement using "SEPARATION ARGUMENT"
# SEPERATION ARGUMENT --> sep = "."

# Without SEPARATION ARGUMENT - sep = " "
print("Milk","Curd","Butter","Paneer","buttermilk","Cheese")

# With SEPARATION ARGUMENT - sep = " "
print("Laptop","Mobile","Mouse","Keyboard","Charger",sep=" ")

# With SEPARATION ARGUMENT - sep = "."
print("Milk","Curd","Butter","Paneer","buttermilk","Cheese",sep = ".")

# With SEPARATION ARGUMENT - sep = "..."
print("Hi","Hi","Hi",sep = "...")